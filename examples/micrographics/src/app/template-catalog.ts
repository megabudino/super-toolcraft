export function templatesForKit(kit: MicrographKitId): readonly MicrographTemplateId[] {
  return kit === "full" ? micrographTemplateIds : kitMembers[kit];
}

export function templateSizeClass(id: MicrographTemplateId): MicrographSizeClass {
  return micrographTemplates.find((template) => template.id === id)?.sizeClass ?? "small";
}

export function templateAspect(id: MicrographTemplateId): number {
  return micrographTemplates.find((template) => template.id === id)?.aspect ?? 1.4;
}

export function isMicrographTemplateId(value: unknown): value is MicrographTemplateId {
  return (
    typeof value === "string" &&
    micrographTemplateIds.includes(value as MicrographTemplateId)
  );
}

export type MicrographTemplateTier = "mega" | "simple";

const megaIds: readonly MicrographTemplateId[] = [
  "arc-lockup",
  "axis-lockup",
  "brand-lockup",
  "lab-plate",
  "lamp-lockup",
  "strip-lockup",
  "studio-lockup",
];

export function templateTier(id: MicrographTemplateId): MicrographTemplateTier {
  return (
    id.startsWith("plate-") || id.startsWith("mega-") || megaIds.includes(id)
      ? "mega"
      : "simple"
  );
}
